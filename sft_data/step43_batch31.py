def make_traj(tid, sc, cat, focus, query, tool_input, products, final_content,
              card_reasons, tool_name="SkuRecallShopping",
              thinking="", multi_turn=False, history=None):
    cards = [
        {"card_id": p["product_id"], "display_price": p["price"], "reason": r}
        for p, r in zip(products, card_reasons)
    ]
    return {
        "trajectory_id": tid,
        "scenario_type": sc,
        "category": cat,
        "quality_label": "good",
        "training_focus": focus,
        "is_multi_turn": multi_turn,
        "conversation_history": history or [],
        "user_query": query,
        "thinking": thinking or f"分析{focus}，调用工具处理 {len(products)} 个结果。",
        "steps": [
            {
                "step_id": 1,
                "step_type": "tool_call",
                "tool_name": tool_name,
                "tool_input": tool_input,
                "tool_output": {"status": "SUCCESS", "products": products},
                "error_type": None
            },
            {
                "step_id": 2,
                "step_type": "final_response",
                "content": final_content,
                "product_cards": cards
            }
        ],
        "final_response": final_content,
        "eval_score": 1.0,
        "sft_source": "claude_local_v1"
    }


