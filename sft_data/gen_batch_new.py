def make_traj(tid, sc, cat, focus, query, tool_input, products, final_content, card_reasons, tool_name="SkuRecallShopping"):
    tool_output_products = []
    for p in products:
        tool_output_products.append({
            "product_id": p["product_id"],
            "title": p["title"],
            "price": p["price"],
            "is_jd_self": p.get("is_jd_self", True),
            "rating": p.get("rating", 4.8),
            "key_specs": p.get("key_specs", ""),
            "sales": p.get("sales", ""),
        })

    product_cards = []
    for p, reason in zip(products, card_reasons):
        product_cards.append({
            "card_id": p["product_id"],
            "display_price": p["price"],
            "reason": reason,
        })

    traj = {
        "trajectory_id": tid,
        "scenario_type": sc,
        "category": cat,
        "quality_label": "good",
        "training_focus": focus,
        "is_multi_turn": False,
        "conversation_history": [],
        "user_query": query,
        "thinking": focus,
        "steps": [
            {
                "step_id": 1,
                "step_type": "tool_call",
                "tool_name": tool_name,
                "tool_input": tool_input,
                "tool_output": {
                    "status": "SUCCESS",
                    "products": tool_output_products,
                },
                "error_type": None,
            },
            {
                "step_id": 2,
                "step_type": "final_response",
                "content": final_content,
                "product_cards": product_cards,
            },
        ],
        "final_response": final_content,
        "eval_score": 1.0,
        "sft_source": "claude_local_v1",
    }
    return traj


