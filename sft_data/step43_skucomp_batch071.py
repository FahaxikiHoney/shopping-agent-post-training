"""
SFT 训练数据生成 - sku_comp 专项批次（sft_skucomp_071 ~ 080）
10 条商品对比场景，覆盖 10 个不同品类和对比维度。
追加写入 trajectories_final.jsonl
"""
import json
from pathlib import Path

OUTPUT_PATH = Path(__file__).parent / "trajectories_final.jsonl"


def make_traj(tid, sc, cat, focus, query, tool_input, products, final_content, card_reasons, tool_name="SkuRecallShopping"):
    """
    构建一条标准 sku_comp SFT 轨迹。
    card_reasons: list of (product_id, display_price, reason)
    products: list of dicts with product_id, title, price, is_platform_self, rating, key_specs, sales
    """
    product_ids = {p["product_id"] for p in products}
    for pid, _, _ in card_reasons:
        assert pid in product_ids, f"card reason 中的 product_id={pid} 不在 products 中"

    product_cards = [
        {"card_id": pid, "display_price": price, "reason": reason}
        for pid, price, reason in card_reasons
    ]

    return {
        "trajectory_id": tid,
        "scenario_type": sc,
        "category": cat,
        "quality_label": "good",
        "training_focus": focus,
        "is_multi_turn": False,
        "conversation_history": [],
        "user_query": query,
        "thinking": f"召回 {len(products)} 款商品，并行对比，给出带倾向性建议的综合分析。",
        "steps": [
            {
                "step_id": 1,
                "step_type": "tool_call",
                "tool_name": tool_name,
                "tool_input": tool_input,
                "tool_output": {
                    "status": "SUCCESS",
                    "products": products
                },
                "error_type": None
            },
            {
                "step_id": 2,
                "step_type": "final_response",
                "content": final_content,
                "product_cards": product_cards
            }
        ],
        "final_response": final_content,
        "eval_score": 1.0,
        "sft_source": "claude_local_v1"
    }


