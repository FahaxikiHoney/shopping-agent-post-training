def make_traj(tid, sc, cat, focus, query, tool_input, products, final_content,
              card_reasons, tool_name="SkuRecallShopping"):
    """构建单条 SFT 训练轨迹 dict。"""
    # 校验 card_reasons 与 products 数量一致
    assert len(card_reasons) == len(products), (
        f"{tid}: card_reasons({len(card_reasons)}) != products({len(products)})"
    )
    # 校验 card_id 与 product_id 一致
    for i, (cr, prod) in enumerate(zip(card_reasons, products)):
        if isinstance(cr, dict):
            assert cr.get("card_id") == prod["product_id"], (
                f"{tid}[{i}]: card_id mismatch {cr.get('card_id')} vs {prod['product_id']}"
            )

    messages = [
        {"role": "user", "content": query},
        {
            "role": "assistant",
            "content": None,
            "tool_calls": [
                {
                    "id": f"call_{tid}",
                    "type": "function",
                    "function": {
                        "name": tool_name,
                        "arguments": json.dumps(tool_input, ensure_ascii=False)
                    }
                }
            ]
        },
        {
            "role": "tool",
            "tool_call_id": f"call_{tid}",
            "content": json.dumps({"products": products}, ensure_ascii=False)
        },
        {"role": "assistant", "content": final_content}
    ]

    return {
        "trajectory_id": tid,
        "scene": sc,
        "category": cat,
        "scene_focus": focus,
        "query": query,
        "tool_name": tool_name,
        "tool_input": tool_input,
        "tool_output": {"products": products},
        "final_content": final_content,
        "card_reasons": card_reasons,
        "messages": messages
    }


